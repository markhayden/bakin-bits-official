/**
 * Regenerates lib/tmux-width-table.ts from the managed tmux: for every
 * codepoint, tmux's own width (its `#{w:}` format, which runs the same
 * width function the grid uses: tmux's default table, then utf8proc) is
 * compared with the grapheme provider's, and the differences are recorded
 * with tmux's width. Context (what tmux combines with the previous cell)
 * is not a scalar width and is left to the grapheme rules; the
 * width-parity integration test pins the remaining differences.
 *
 *   TERMINAL_TMUX=~/.bakin/bin/tmux bun plugins/terminal/scripts/generate-tmux-widths.ts
 *
 * Rerun when the tmux pin or the grapheme addon changes (the width-parity
 * integration test fails then).
 */
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import headless from '@xterm/headless'
import { loadGraphemeProvider } from '../lib/unicode-widths'

/** The source of lib/tmux-width-table.ts as the tmux at `tmux` measures it. */
export function renderTmuxWidthTable(tmux: string): string {
  const version = Bun.spawnSync([tmux, '-V']).stdout.toString().trim()
  // A short path: tmux sockets are limited to about 100 bytes.
  const root = mkdtempSync('/tmp/bakin-widths-')
  const socket = join(root, 's')
  const run = (...args: string[]) => {
    const result = Bun.spawnSync([tmux, '-S', socket, '-f', '/dev/null', ...args], { env: { PATH: '/usr/bin:/bin', HOME: root, LANG: 'en_US.UTF-8' } })
    if (result.exitCode !== 0) throw new Error(`tmux ${args[0]}: ${result.stderr.toString()}`)
    return result.stdout.toString()
  }
  const differing: [number, number][] = []
  try {
    run('new-session', '-d', '-s', 'w', 'sleep 3600')
    const base = loadGraphemeProvider(new headless.Terminal({ allowProposedApi: true }) as never)
    // tmux's width for each codepoint, one batch per command file.
    const tmuxWidths = (codepoints: number[]): number[] => {
      const file = join(root, 'batch.conf')
      writeFileSync(file, codepoints.map((codepoint, i) => `set -g @c${i} '${String.fromCodePoint(codepoint)}'`).join('\n') + '\n')
      run('source-file', file)
      return run('display', '-p', codepoints.map((_, i) => `#{w:@c${i}}`).join(' ')).trim().split(' ').map(Number)
    }
    // Printable codepoints from U+00A0 through plane 3, and the tag/variation plane (no surrogates).
    for (const [first, last] of [[0xa0, 0x3134f], [0xe0000, 0xe01ef]] as const) {
      const all: number[] = []
      for (let codepoint = first; codepoint <= last; codepoint++) if (codepoint < 0xd800 || codepoint > 0xdfff) all.push(codepoint)
      for (let i = 0; i < all.length; i += 500) {
        const batch = all.slice(i, i + 500)
        const widths = tmuxWidths(batch)
        if (widths.length !== batch.length) throw new Error(`tmux returned ${widths.length} widths for ${batch.length} codepoints at U+${batch[0]!.toString(16)}`)
        batch.forEach((codepoint, k) => {
          const ours = base.wcwidth(codepoint)
          const theirs = widths[k]!
          // A spacing character the grapheme rules treat as zero-width joins
          // its letter either way; that is context, not a width.
          if (theirs !== ours && ours !== 0) differing.push([codepoint, theirs])
        })
      }
    }
  } finally {
    Bun.spawnSync([tmux, '-S', socket, 'kill-server'])
    rmSync(root, { recursive: true, force: true })
  }
  const ranges: [number, number, number][] = []
  for (const [codepoint, width] of differing) {
    const previous = ranges.at(-1)
    if (previous && previous[1] === codepoint - 1 && previous[2] === width) previous[1] = codepoint
    else ranges.push([codepoint, codepoint, width])
  }
  const hex = (value: number) => '0x' + value.toString(16).toUpperCase()
  return `// Generated by scripts/generate-tmux-widths.ts — do not edit by hand.
export const TMUX_WIDTH_SOURCE = '${version} (utf8proc), @xterm/addon-unicode-graphemes 0.4.0'
/** [first, last, width]: codepoints whose width differs between tmux and the grapheme provider, with tmux's width. */
export const TMUX_WIDTHS: readonly (readonly [number, number, 0 | 1 | 2])[] = [
${ranges.map(([first, last, width]) => `  [${hex(first)}, ${hex(last)}, ${width}],`).join('\n')}
]
`
}

if (import.meta.main) {
  const tmux = process.env.TERMINAL_TMUX
  if (!tmux) throw new Error('set TERMINAL_TMUX to the managed tmux binary')
  writeFileSync(join(import.meta.dir, '../lib/tmux-width-table.ts'), renderTmuxWidthTable(tmux))
}
